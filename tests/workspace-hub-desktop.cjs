const {_electron}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');

(async()=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'guanlan-hub-'));
 const env={...process.env,DIRECTOR_DATA_DIR:root,DIRECTOR_HEADLESS:'1'};
 delete env.ELECTRON_RUN_AS_NODE;
 const app=await _electron.launch({args:[path.resolve('.')],env});
 try{
  const page=await app.firstWindow(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>typeof PRODUCT!=='undefined'&&PRODUCT.ready);
  await page.evaluate(()=>createSample());
  await page.evaluate(async()=>{S.project.jobs.unshift({id:'hub-test-job',name:'分镜生成测试任务',startedAt:new Date().toISOString(),status:'completed'},{id:'hub-failed-job',name:'失败任务测试',startedAt:new Date().toISOString(),status:'failed',error:'模型连接不可用'});await persist();render();});
  assert.match(await page.locator('#save-status').innerText(),/已保存 ·/);
  assert.equal(await page.locator('.hub-header-actions').count(),1);
  assert.equal(await page.locator('#nav [data-page="dashboard"]').count(),1);
  await page.locator('#nav [data-page="projects"]').click();
  assert.equal(await page.evaluate(()=>S.page),'projects');
  assert.equal(await page.locator('.hub-project-card').count(),1);
  await fs.mkdir(path.resolve('audit-evidence/after'),{recursive:true});
  await page.screenshot({animations:'disabled',path:path.resolve('audit-evidence/after/hub-projects.png')});
  await page.locator('#hub-project-query').fill('没有这个项目');
  assert.match(await page.locator('.hub-projects').innerText(),/没有匹配项目/);
  await page.locator('#hub-project-query').fill('');
  await page.locator('[data-action="hub-queue"]').click();
  await page.waitForFunction(()=>HUB.panel==='queue'&&!HUB.loading);
  await page.locator('#hub-panel [data-filter="done"]').click();
  assert.match(await page.locator('#hub-panel').innerText(),/分镜生成测试任务/);
  await page.locator('#hub-panel [data-filter="failed"]').click();
  assert.match(await page.locator('#hub-panel').innerText(),/模型连接不可用/);
  await page.locator('#hub-panel [data-filter="done"]').click();
  await page.screenshot({animations:'disabled',path:path.resolve('audit-evidence/after/hub-queue.png')});
  await page.locator('#hub-panel [data-action="hub-open-task"]').click();
  assert.equal(await page.evaluate(()=>S.page),'history');
  await page.locator('[data-action="hub-messages"]').click();
  assert.match(await page.locator('#hub-panel').innerText(),/分镜生成测试任务/);
  await page.locator('#hub-panel [data-action="hub-open-notice"]').first().click();
  assert.equal(await page.evaluate(()=>S.page),'history');
  await page.locator('[data-action="hub-messages"]').click();
  await page.locator('#hub-panel [data-action="hub-read"]').click();
  assert.equal(await page.locator('.hub-notice.unread').count(),0);
  await page.locator('[data-action="hub-help"]').click();
  assert.match(await page.locator('#hub-panel').innerText(),/使用指南/);
  await page.locator('#hub-panel [data-action="hub-close"]').click();
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1040,720));
  await page.evaluate(()=>act('page',{page:'projects'}));
  assert.ok(await page.locator('main').evaluate(el=>el.scrollWidth<=el.clientWidth+2),'窄窗口不得水平溢出');
  await page.locator('.hub-page-head [data-action="new-project"]').click();
  await page.locator('#new-name').fill('错误字幕输入');
  await page.locator('#new-mode').selectOption('subtitle');
  await page.evaluate(()=>{NEW_PROJECT.imported={name:'notes.txt',text:'字幕文字'};});
  await page.locator('#modal-submit').click();
  assert.equal(await page.evaluate(()=>S.projects.some(x=>x.name==='错误字幕输入')),false);
  await page.locator('#new-mode').selectOption('canvas');
  await page.locator('#new-name').fill('空白画布测试');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(()=>S.page==='canvas'&&S.project?.name==='空白画布测试');
  await page.evaluate(()=>act('page',{page:'projects'}));
  assert.equal(await page.locator('.hub-project-card').count(),2);
  await page.locator('.hub-project-card').filter({hasText:'空白画布测试'}).locator('[data-action="hub-delete-project"]').click();
  assert.match(await page.locator('#modal-body').innerText(),/移入本机回收站/);
  await page.locator('#modal-submit').click();
  await page.waitForFunction(()=>S.projects.length===1&&S.page==='projects');
  await page.locator('[data-action="hub-trash"]').click();
  assert.match(await page.locator('#modal-body').innerText(),/空白画布测试/);
  await page.locator('[data-action="hub-restore-project"]').click();
  await page.waitForFunction(()=>S.projects.length===2);
  await page.locator('.hub-project-card').filter({hasText:'空白画布测试'}).locator('[data-action="hub-delete-project"]').click();
  await page.locator('#modal-submit').click();
  await page.locator('[data-action="hub-trash"]').click();
  await page.locator('[data-action="hub-purge-project"]').click();
  await page.locator('#hub-purge-name').fill('空白画布测试');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(()=>!$('modal').open);
  assert.equal((await page.evaluate(()=>call('projects:archived'))).length,0);
  await page.reload();
  await page.waitForFunction(()=>typeof PRODUCT!=='undefined'&&PRODUCT.ready);
  assert.equal(await page.evaluate(()=>S.projects.length),1);
  assert.deepEqual(errors,[]);
  console.log('PASS 项目库检索、删除与回收站、顶栏状态、跨页面任务和消息及窄窗口');
 }finally{await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});


