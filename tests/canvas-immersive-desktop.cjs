const {_electron}=require('@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');

(async()=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'guanlan-canvas-immersive-'));
 const env={...process.env,DIRECTOR_DATA_DIR:root,DIRECTOR_HEADLESS:'1'};
 delete env.ELECTRON_RUN_AS_NODE;
 const app=await _electron.launch({args:[path.resolve('.')],env});
 try{
  const page=await app.firstWindow(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>typeof PRODUCT!=='undefined'&&PRODUCT.ready);
  await page.evaluate(()=>createSample());
  await page.locator('#nav [data-page="canvas"]').click();
  await page.locator('.canvas-immersive-add-trigger').waitFor();
  assert.equal(await page.locator('.shell>aside').isVisible(),false);
  assert.equal(await page.locator('.canvas-immersive-add-menu').isVisible(),false);
  const widths=await page.evaluate(()=>({main:document.querySelector('main').getBoundingClientRect().width,viewport:innerWidth}));
  assert.ok(widths.main>=widths.viewport-2,JSON.stringify(widths));
  await page.locator('.canvas-immersive-add-trigger').click();
  assert.equal(await page.locator('.canvas-immersive-add-menu').isVisible(),true);
  await page.locator('.canvas-immersive-add-menu [data-action="flow-add"][data-type="prompt"]').click();
  await page.locator('#flow-text').fill('人物背对镜头，向窗边走两步');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(()=>S.project.canvasGraph.nodes.some(n=>n.type==='prompt'&&n.text.includes('窗边')));
  assert.equal(await page.locator('.canvas-immersive-add-menu').isVisible(),false);
  assert.match(await page.locator('.canvas-immersive-preview').first().innerText(),/窗边/);
  assert.equal(await page.locator('.canvas-immersive-node-tools [data-action="canvas-node-copy"]').count(),1);
  const shot=await page.evaluate(()=>DW.rows(S.project)[0]?.sh);
  assert.ok(shot,'示例项目应包含镜头');
  await page.evaluate(shotId=>{const g=flowGraph();g.nodes.push({id:'bound-preview-test',type:'generate',x:680,y:240,title:'',text:'',media:'',assetId:'',shotId});render();},shot.id);
  assert.match(await page.locator('[data-flow-node="bound-preview-test"] .canvas-immersive-preview').innerText(),new RegExp(shot.frame.slice(0,8)));
  const alignment=await page.evaluate(()=>{const source=flowGraph().nodes.find(n=>n.type==='prompt'),target=flowNode('bound-preview-test');flowGraph().edges.push({from:source.id,to:target.id});canvasDrawLinks();const a=document.querySelector(`[data-flow-node="${source.id}"]`),port=a.querySelector('.canvas-port-out'),edge=document.querySelector(`[data-link-from="${source.id}"][data-link-to="bound-preview-test"]`);return {actual:Number(edge?.getAttribute('d')?.match(/^M [\d.]+ ([\d.]+)/)?.[1]),expected:parseFloat(a.style.top)+port.offsetTop+port.offsetHeight/2};});
  assert.ok(Math.abs(alignment.actual-alignment.expected)<1,'连线应从端口圆点中心发出');
  const themeMarks=await page.evaluate(()=>['deepsea','ink','stellar'].map(skin=>{document.documentElement.dataset.skin=skin;return getComputedStyle(document.querySelector('.canvas-immersive-brand-mark')).backgroundColor;}));
  assert.equal(new Set(themeMarks).size,3,'三套主题的画布品牌色应各自匹配');
  await page.locator('[data-flow-node="bound-preview-test"] [data-action="canvas-node-copy"]').click();
  await page.waitForFunction(()=>S.project.canvasGraph.nodes.some(n=>n.title.includes('副本')));
  const copied=await page.evaluate(()=>S.project.canvasGraph.nodes.find(n=>n.title.includes('副本')));
  assert.match(copied.title,/生成.*副本/);
  assert.ok(copied.x>=1000,'复制节点应与源节点错开');
  assert.equal(await page.locator('#canvas-inspector').isVisible(),false,'复制节点不应自动弹出遮挡卡片的详情');
  await page.locator('[data-flow-node="bound-preview-test"]').click({position:{x:20,y:20}});
  await page.locator('[data-action="canvas-inspector-close"]').click();
  await page.screenshot({path:path.resolve('docs/assets/canvas-immersive.png')});
  await page.locator('[data-action="canvas-immersive-nav"]').click();
  assert.equal(await page.locator('.canvas-immersive-nav').isVisible(),true);
  await page.locator('#shot-canvas-stage').click({button:'right',position:{x:400,y:220}});
  assert.equal(await page.locator('.canvas-immersive-add-menu').isVisible(),true);
  const rightPoint=await page.evaluate(()=>{const v=canvasViewport();return {x:(400-v.x)/v.z,y:(220-v.y)/v.z};});
  await page.locator('.canvas-immersive-add-menu [data-action="flow-add"][data-type="prompt"]').click();
  await page.locator('#flow-text').fill('从右键位置创建');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(()=>S.project.canvasGraph.nodes.some(n=>n.text==='从右键位置创建'));
  const rightClickNode=await page.evaluate(()=>S.project.canvasGraph.nodes.find(n=>n.text==='从右键位置创建'));
  assert.ok(Math.abs(rightClickNode.x-rightPoint.x)<=8&&Math.abs(rightClickNode.y-rightPoint.y)<=8,'右键添加应使用点击处的画布坐标');
  await page.setViewportSize({width:980,height:700});
  assert.equal(await page.evaluate(()=>innerWidth),980);
  assert.ok(await page.locator('main').evaluate(el=>el.scrollWidth<=el.clientWidth+2),'窄窗口不应横向溢出');
  assert.equal(await page.locator('.canvas-immersive-add-trigger').isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log('PASS 沉浸画布全宽、添加菜单、内容节点、导航与窄窗口');
 }finally{await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
